"""
CloudFront signed URLs
========================
The existing `presigned_url()` in storage_service.py generates a presigned
*S3* URL — it works, but it points directly at the S3 bucket hostname,
bypassing any CloudFront distribution sitting in front of it. That defeats
the entire purpose of having a CDN: every "view complaint image" request
in the dashboard/mobile app would hit S3 origin directly instead of being
served from edge cache, and the bucket's hostname (and therefore its
existence/region) is exposed to every client.

This module is the CDN-aware alternative: signs a CloudFront URL using a
key-pair, so requests actually route through CloudFront's edge network and
only fall through to S3 origin on a cache miss.

This is opt-in — only used when CLOUDFRONT_DOMAIN and the signing key are
configured. Without them, callers should keep using StorageService's
existing S3-presigned-URL path. See backend/.env.example for the new
fields this introduces.
"""

from __future__ import annotations

import datetime
import logging

from app.core.config import settings

logger = logging.getLogger(__name__)


def is_cloudfront_configured() -> bool:
    return bool(
        getattr(settings, "CLOUDFRONT_DOMAIN", "")
        and getattr(settings, "CLOUDFRONT_KEY_PAIR_ID", "")
        and getattr(settings, "CLOUDFRONT_PRIVATE_KEY", "")
    )


def _load_private_key():
    """
    Load the RSA private key used to sign CloudFront URLs.
    CLOUDFRONT_PRIVATE_KEY holds PEM content directly (matching the same
    "paste as a single env var" pattern already used for
    FIREBASE_CREDENTIALS_JSON elsewhere in this config) rather than a
    filesystem path, so this works identically whether secrets come from
    a local .env or from AWS Secrets Manager via secrets_provider.py.
    """
    from cryptography.hazmat.primitives import serialization

    pem_bytes = settings.CLOUDFRONT_PRIVATE_KEY.encode()
    return serialization.load_pem_private_key(pem_bytes, password=None)


def _rsa_signer(message: bytes) -> bytes:
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.asymmetric import padding

    private_key = _load_private_key()
    return private_key.sign(message, padding.PKCS1v15(), hashes.SHA1())


def generate_signed_url(
    object_key: str,
    expiry_seconds: int = 3600,
) -> str:
    """
    Generate a CloudFront signed URL for `object_key`, valid for
    `expiry_seconds`. Falls back to raising — callers should check
    `is_cloudfront_configured()` first, or catch and fall back to
    StorageService.presigned_url() for the direct-S3 path.
    """
    if not is_cloudfront_configured():
        raise RuntimeError(
            "CloudFront signing is not configured — set CLOUDFRONT_DOMAIN, "
            "CLOUDFRONT_KEY_PAIR_ID, and CLOUDFRONT_PRIVATE_KEY, or use "
            "StorageService.presigned_url() for direct S3 access instead."
        )

    from botocore.signers import CloudFrontSigner

    url = f"https://{settings.CLOUDFRONT_DOMAIN.rstrip('/')}/{object_key}"
    expire_at = datetime.datetime.now(datetime.timezone.utc) + datetime.timedelta(
        seconds=expiry_seconds
    )

    signer = CloudFrontSigner(settings.CLOUDFRONT_KEY_PAIR_ID, _rsa_signer)
    signed_url = signer.generate_presigned_url(url, date_less_than=expire_at)

    return signed_url


def generate_signed_url_with_fallback(
    object_key: str,
    s3_presigned_fallback: str,
    expiry_seconds: int = 3600,
) -> str:
    """
    Convenience wrapper: try CloudFront signing, fall back to the direct
    S3 presigned URL (already generated by the caller via
    StorageService.presigned_url()) if CloudFront isn't configured or
    signing fails for any reason. This is the function actual call sites
    should use — it never raises.
    """
    if not is_cloudfront_configured():
        return s3_presigned_fallback

    try:
        return generate_signed_url(object_key, expiry_seconds)
    except Exception as exc:
        logger.warning(
            "CloudFront signing failed for '%s' — falling back to direct S3 presigned URL: %s",
            object_key, exc,
        )
        return s3_presigned_fallback
